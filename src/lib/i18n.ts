export type TranslationKey = keyof typeof en;

const dict: Record<Locale, Record<TranslationKey, string>> = { en, zh };

/**
 * Returns a lookup bound to one locale. `{name}` placeholders are filled from
 * `vars`; a missing key returns the key itself so a gap is loud, not silent.
 */
export function useTranslations(lang: Locale) {
  const table = dict[lang] ?? dict[DEFAULT_LOCALE];
  return function t(key: TranslationKey, vars?: Record<string, string | number>): string {
    const raw = table[key] ?? dict[DEFAULT_LOCALE][key] ?? key;
    if (!vars) return raw;
    return raw.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m));
  };
}
