/**
 * Two locales, one set of templates.
 *
 * Short UI copy lives in the dictionary below. Long-form prose (the about
 * page, the submit guide) does NOT — an essay pushed through a key/value
 * table reads like a translation of a translation, so those pages keep a
 * hand-written file per locale instead.
 */

export const LOCALES = ['en', 'zh'] as const;
export type Locale = (typeof LOCALES)[number];

export const DEFAULT_LOCALE: Locale = 'en';

/** `lang` attribute and hreflang value for each locale. */
export const HTML_LANG: Record<Locale, string> = { en: 'en', zh: 'zh-CN' };
export const OG_LOCALE: Record<Locale, string> = { en: 'en_US', zh: 'zh_CN' };
export const LOCALE_NAME: Record<Locale, string> = { en: 'English', zh: '中文' };

/** Keeps page URLs aligned with Astro's directory output and the sitemap. */
export function normalizePagePath(path: string): string {
  const match = path.match(/^([^?#]*)([?#].*)?$/);
  const pathname = match?.[1] || '/';
  const suffix = match?.[2] ?? '';
  const normalized = pathname === '/' || pathname.endsWith('/') ? pathname : `${pathname}/`;
  return `${normalized}${suffix}`;
}

/**
 * English owns the bare paths (`prefixDefaultLocale: false`), so only Chinese
 * carries a prefix. Every internal link goes through this.
 */
export function localePath(lang: Locale, path: string): string {
  const clean = normalizePagePath(path.startsWith('/') ? path : `/${path}`);
  if (lang === DEFAULT_LOCALE) return clean;
  return clean === '/' ? '/zh/' : `/zh${clean}`;
}

/** Strips the locale prefix, giving the path as the default locale sees it. */
export function stripLocale(pathname: string): string {
  const stripped = pathname.replace(/^\/zh(?=\/|$)/, '');
  return stripped === '' ? '/' : stripped;
}

/** Reads the locale out of a URL path. Astro.currentLocale can be undefined. */
export function localeFromPath(pathname: string): Locale {
  return /^\/zh(\/|$)/.test(pathname) ? 'zh' : 'en';
}

/**
 * Plugin description for a locale: the machine translation on zh when one
 * exists, otherwise the original npm text. Lives here (not in plugins.ts) so
 * client islands can import it without pulling the whole dataset in.
 */
export function pluginDescription(
  p: { description: string | null; descriptionZh?: string | null },
  lang: Locale,
): string | null {
  return (lang === 'zh' && p.descriptionZh) || p.description;
}

/** True when `pluginDescription` would return a machine translation. */
export function isTranslated(p: { description: string | null; descriptionZh?: string | null }, lang: Locale): boolean {
  return lang === 'zh' && Boolean(p.descriptionZh) && Boolean(p.description);
}

